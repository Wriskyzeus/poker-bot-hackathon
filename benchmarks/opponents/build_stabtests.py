"""Render the TASK-010 stab-regression opponents from _stabtest_src.py (benchmark-only; idempotent).
Usage: python benchmarks/opponents/build_stabtests.py"""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__))
NAMES = ["checkfold90", "checkcall50", "checktrap", "shifter"]

def render(name):
    src = open(os.path.join(HERE, "_stabtest_src.py")).read()
    out, n = re.subn(r'^PROFILE = ".*?"', 'PROFILE = "%s"' % name, src, count=1, flags=re.M)
    assert n == 1
    return "# GENERATED by build_stabtests.py from _stabtest_src.py -- edit the source, not this file.\n" + out

def main():
    for n in NAMES:
        d = os.path.join(HERE, n); os.makedirs(d, exist_ok=True)
        open(os.path.join(d, "bot.py"), "w").write(render(n)); print("wrote", d)

if __name__ == "__main__":
    main()
