"""Render the TASK-006 adversary bot folders from _adversary_src.py (each bot.py is self-contained).
Usage: python benchmarks/opponents/build_adversaries.py   (idempotent; benchmark-only, never touches my_bots/)"""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__))
NAMES = ["bluffer_low", "bluffer_mid", "bluffer_high", "pressure", "adaptive"]

def render(name):
    src = open(os.path.join(HERE, "_adversary_src.py")).read()
    out, n = re.subn(r'^PROFILE = ".*?"', 'PROFILE = "%s"' % name, src, count=1, flags=re.M)
    assert n == 1
    return "# GENERATED by build_adversaries.py from _adversary_src.py -- edit the source, not this file.\n" + out

def main():
    for n in NAMES:
        d = os.path.join(HERE, n); os.makedirs(d, exist_ok=True)
        open(os.path.join(d, "bot.py"), "w").write(render(n))
        print("wrote", d)

if __name__ == "__main__":
    main()
